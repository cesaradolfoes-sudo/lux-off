create extension if not exists pgcrypto;
create table if not exists public.admin_users (
 user_id uuid primary key references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
create table if not exists public.products (
 id bigint generated by default as identity primary key,
 brand text not null, name text not null, description text not null default '',
 price numeric(12,2) not null check(price>0),
 stock integer not null default 0 check(stock>=0),
 reserved integer not null default 0 check(reserved>=0 and reserved<=stock),
 active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.orders (
 id uuid primary key default gen_random_uuid(),
 customer_name text not null, customer_phone text not null,
 status text not null default 'reserved' check(status in ('reserved','confirmed','cancelled')),
 total numeric(12,2) not null default 0,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.order_items (
 id bigint generated by default as identity primary key,
 order_id uuid not null references public.orders(id) on delete cascade,
 product_id bigint not null references public.products(id),
 quantity integer not null check(quantity>0), unit_price numeric(12,2) not null check(unit_price>0)
);
alter table public.admin_users enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products" on public.products for select to anon, authenticated using(active=true);
drop policy if exists "Admins can manage products" on public.products;
create policy "Admins can manage products" on public.products for all to authenticated using(exists(select 1 from public.admin_users a where a.user_id=auth.uid())) with check(exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
revoke all on public.orders from anon,authenticated;
revoke all on public.order_items from anon,authenticated;
revoke all on public.admin_users from anon,authenticated;
grant select on public.products to anon,authenticated;
grant insert,update,delete on public.products to authenticated;
grant usage,select on sequence public.products_id_seq to authenticated;
grant usage,select on sequence public.order_items_id_seq to authenticated;
create or replace function public.reserve_order(p_customer_name text,p_customer_phone text,p_items jsonb)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_order_id uuid; v_item jsonb; v_product public.products%rowtype; v_qty integer; v_total numeric(12,2):=0;
begin
 if length(trim(coalesce(p_customer_name,'')))<2 or length(trim(coalesce(p_customer_phone,'')))<7 then raise exception 'Escribe un nombre y teléfono válidos.'; end if;
 if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 or jsonb_array_length(p_items)>20 then raise exception 'El carrito está vacío o contiene demasiados productos.'; end if;
 insert into public.orders(customer_name,customer_phone,status,total) values(trim(p_customer_name),trim(p_customer_phone),'reserved',0) returning id into v_order_id;
 for v_item in select value from jsonb_array_elements(p_items) loop
  v_qty:=(v_item->>'quantity')::integer;
  if v_qty<1 or v_qty>10 then raise exception 'Cantidad no válida.'; end if;
  select * into v_product from public.products where id=(v_item->>'product_id')::bigint and active=true for update;
  if not found then raise exception 'Uno de los perfumes ya no está disponible.'; end if;
  if v_product.stock-v_product.reserved<v_qty then raise exception 'Stock insuficiente para: % %.',v_product.brand,v_product.name; end if;
  update public.products set reserved=reserved+v_qty where id=v_product.id;
  insert into public.order_items(order_id,product_id,quantity,unit_price) values(v_order_id,v_product.id,v_qty,v_product.price);
  v_total:=v_total+v_product.price*v_qty;
 end loop;
 update public.orders set total=v_total,updated_at=now() where id=v_order_id;
 return jsonb_build_object('order_id',v_order_id,'total',v_total,'status','reserved');
end $$;
create or replace function public.confirm_order(p_order_id uuid)
returns void language plpgsql security definer set search_path=public as $$
declare v_order public.orders%rowtype; v_item record;
begin
 if not exists(select 1 from public.admin_users where user_id=auth.uid()) then raise exception 'No autorizado.'; end if;
 select * into v_order from public.orders where id=p_order_id for update;
 if not found or v_order.status<>'reserved' then raise exception 'El pedido no existe o ya fue procesado.'; end if;
 for v_item in select product_id,quantity from public.order_items where order_id=p_order_id loop
  update public.products set reserved=reserved-v_item.quantity,stock=stock-v_item.quantity where id=v_item.product_id and reserved>=v_item.quantity and stock>=v_item.quantity;
  if not found then raise exception 'No se pudo actualizar el inventario.'; end if;
 end loop;
 update public.orders set status='confirmed',updated_at=now() where id=p_order_id;
end $$;
create or replace function public.cancel_order(p_order_id uuid)
returns void language plpgsql security definer set search_path=public as $$
declare v_order public.orders%rowtype; v_item record;
begin
 if not exists(select 1 from public.admin_users where user_id=auth.uid()) then raise exception 'No autorizado.'; end if;
 select * into v_order from public.orders where id=p_order_id for update;
 if not found or v_order.status<>'reserved' then raise exception 'El pedido no existe o ya fue procesado.'; end if;
 for v_item in select product_id,quantity from public.order_items where order_id=p_order_id loop
  update public.products set reserved=reserved-v_item.quantity where id=v_item.product_id and reserved>=v_item.quantity;
  if not found then raise exception 'No se pudo liberar la reserva.'; end if;
 end loop;
 update public.orders set status='cancelled',updated_at=now() where id=p_order_id;
end $$;
create or replace function public.admin_list_orders()
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_result jsonb;
begin
 if not exists(select 1 from public.admin_users where user_id=auth.uid()) then raise exception 'No autorizado.'; end if;
 select coalesce(jsonb_agg(jsonb_build_object('id',o.id,'customer_name',o.customer_name,'customer_phone',o.customer_phone,'status',o.status,'total',o.total,'created_at',o.created_at,'order_items',(select coalesce(jsonb_agg(jsonb_build_object('quantity',i.quantity,'unit_price',i.unit_price,'products',jsonb_build_object('brand',p.brand,'name',p.name))),'[]'::jsonb) from public.order_items i join public.products p on p.id=i.product_id where i.order_id=o.id)) order by o.created_at desc),'[]'::jsonb) into v_result from public.orders o;
 return v_result;
end $$;
